export function getInitialLang() {
  const saved = localStorage.getItem("omnipanel_lang");
  if (saved === "zh" || saved === "en") return saved;
  const navLang = (navigator.language || "").toLowerCase();
  return navLang.startsWith("zh") ? "zh" : "en";
}

export function t(lang, key, vars = null) {
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.en;
  let str = dict[key] ?? TRANSLATIONS.en[key] ?? key;
  if (vars) {
    Object.entries(vars).forEach(([k, v]) => {
      str = str.replaceAll(`{${k}}`, String(v));
    });
  }
  return str;
}

export function trRisk(lang, label) {
  if (lang === "zh") return RISK_ZH_MAP[label] || label;
  return label;
}

export function trAd(lang, status) {
  const m = AD_LABEL_MAP[lang] || AD_LABEL_MAP.en;
  return m[status] || status;
}

export function applyStaticI18n(lang) {
  document.documentElement.lang = lang === "zh" ? "zh-CN" : "en";
  document.title = t(lang, "page_title");
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const k = el.getAttribute("data-i18n");
    if (k) el.textContent = t(lang, k);
  });
  document.querySelectorAll("[data-i18n-ph]").forEach((el) => {
    const k = el.getAttribute("data-i18n-ph");
    if (k) el.setAttribute("placeholder", t(lang, k));
  });
  document.querySelectorAll("[data-i18n-title]").forEach((el) => {
    const k = el.getAttribute("data-i18n-title");
    if (k) el.setAttribute("title", t(lang, k));
  });
}
